using System.Net;

namespace Hiero.Mirror;
/// <summary>
/// Exception raised when a mirror request or simulated evm call has failed.
/// </summary>
/// <remarks>
/// <para>
/// Thrown by <see cref="MirrorRestClient"/> extension methods when the
/// mirror node REST API returns an HTTP error response. The
/// <see cref="StatusCode"/> property carries the HTTP status and
/// <see cref="Details"/> contains the structured error payload returned
/// by the mirror node (if any).
/// </para>
/// <para><strong>Transient codes (safe to retry):</strong>
/// <see cref="HttpStatusCode.TooManyRequests"/> (429),
/// <see cref="HttpStatusCode.ServiceUnavailable"/> (503),
/// <see cref="HttpStatusCode.GatewayTimeout"/> (504). Mirror nodes
/// enforce rate limits; back off and retry.</para>
/// <para><strong>Not found:</strong> a lookup of a single entity or
/// transaction returns <c>null</c> (or an empty result) for an HTTP 404
/// rather than throwing. Either way, "not found" is not proof that
/// something does not exist: the mirror node trails consensus by seconds or
/// more, so a transaction submitted moments ago may simply not have arrived
/// yet. Never treat it as proof that a transaction failed; see
/// <see cref="ConsensusException"/> for how to settle an unknown outcome.</para>
/// <para><strong>Bad request (400):</strong> usually a malformed query; check
/// the filter parameters. A simulated EVM call
/// (<see cref="EvmCallResultExtensions.CallEvmAsync(MirrorRestClient, EvmCallData, CancellationToken)"/>)
/// also reports a contract revert this way, with the revert data in
/// <see cref="Details"/>; retrying returns the same answer.</para>
/// </remarks>
public class MirrorException : Exception
{
    /// <summary>
    /// The http status code returned from the mirror node request.
    /// </summary>
    public HttpStatusCode StatusCode { get; private set; }
    /// <summary>
    /// The error details returned by the mirror node.
    /// </summary>
    public MirrorError[] Details { get; private set; }
    /// <summary>
    /// Public Constructor.
    /// </summary>
    /// <param name="message">
    /// The message generated by the library describing the
    /// condition that raised the exception.
    /// </param>
    /// <param name="details">The error details returned from the mirror node.</param>
    /// <param name="code">The HTTP status code returned.</param>
    public MirrorException(string message, MirrorError[] details, HttpStatusCode code) : base(message)
    {
        StatusCode = code;
        Details = details;
    }
}