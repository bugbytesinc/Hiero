namespace Hiero;
/// <summary>
/// Exception thrown when the gateway node accepted a transaction but its
/// outcome could not be confirmed: the receipt was still pending when the
/// retries ran out, the node stayed too busy to return one, or the node
/// reported the transaction expired or had no receipt for it
/// (<see cref="ResponseCode.ReceiptNotFound"/>).
/// </summary>
/// <remarks>
/// <para>
/// <strong>The outcome is unknown: the transaction may have executed.</strong>
/// Do not resubmit it. A resubmission is a new transaction with a new
/// <see cref="TransactionId"/>, so if the first one executed, the value
/// moves twice. Do not report it as failed either. Treat it as pending and
/// settle it on a mirror node by <see cref="TransactionId"/>, as in the
/// example below.
/// </para>
/// <para>
/// The transaction can no longer execute once the mirror node's latest
/// consensus time is past its valid start plus the
/// <see cref="IConsensusContext.TransactionDuration"/> it was sent with,
/// plus a margin (60 seconds in the example) for mirror replicas that lag
/// one another. Read that clock before looking the transaction up, so the
/// lookup sees at least everything the mirror held at that time. Until
/// then, "not found" on the mirror means "not yet", not "never". Judge it
/// by the mirror's clock, never the local one.
/// </para>
/// <para>
/// The same holds for a <see cref="PrecheckException"/> whose status
/// describes the node or the network rather than the transaction, and for
/// any other exception raised once the transaction may have been sent,
/// such as a cancellation.
/// </para>
/// <para>
/// Seen often on a healthy network, this exception usually means the retry
/// window is shorter than the transaction's validity: see
/// <see cref="IConsensusContext.RetryCount"/>.
/// </para>
/// </remarks>
/// <example>
/// Classify the ending of a transfer whose transaction id was chosen up front:
/// <code source="../../samples/DocSnippets/OutcomeSnippets.cs" region="SubmitAndClassify" language="csharp"/>
/// Settle an unknown outcome on a mirror node:
/// <code source="../../samples/DocSnippets/OutcomeSnippets.cs" region="ResolveOutcome" language="csharp"/>
/// </example>
public sealed class ConsensusException : Exception
{
    /// <summary>
    /// The last <see cref="ResponseCode"/> the node returned for the
    /// transaction.  It is not a verdict: the outcome is unknown.
    /// </summary>
    public ResponseCode Status { get; private set; }
    /// <summary>
    /// The transaction ID generated by the library (or client code)
    /// identifying the request: the id to settle the outcome by on a
    /// mirror node.
    /// </summary>
    public TransactionId TransactionId { get; private set; }
    /// <summary>
    /// Internal Constructor.
    /// </summary>
    /// <param name="message">
    /// The message generated by the library describing the 
    /// condition that raised the exception.
    /// </param>
    /// <param name="transaction">
    /// The transaction ID of the request whose outcome is unknown.
    /// </param>
    /// <param name="code">
    /// The last <see cref="ResponseCode"/> the node gave before the SDK
    /// stopped waiting, such as <see cref="ResponseCode.Unknown"/> for a
    /// receipt still pending.
    /// </param>
    internal ConsensusException(string message, TransactionId transaction, ResponseCode code) : base(message)
    {
        Status = code;
        TransactionId = transaction;
    }
}