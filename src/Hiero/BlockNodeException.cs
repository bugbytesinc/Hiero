using System.Diagnostics.CodeAnalysis;

namespace Hiero;

/// <summary>
/// Represents a failure reported by (or detected while communicating
/// with) a Hiero Block Node.
/// </summary>
/// <remarks>
/// <para>
/// Thrown by the <see cref="BlockNodeClient"/> methods when a request
/// fails or a block stream faults.  For streaming methods, blocks that
/// were already delivered to the destination channel before the fault
/// are still valid — only the stream itself is broken.
/// </para>
/// <para>
/// Inspect <see cref="Code"/> to decide how to recover; each
/// <see cref="BlockNodeExceptionCode"/> value documents whether the
/// condition is transient (retry) or permanent (correct the request).
/// </para>
/// </remarks>
[Experimental("HIERO001", UrlFormat = "https://github.com/bugbytesinc/Hiero/blob/main/docs/blocknode-client-plan.md")]
public sealed class BlockNodeException : Exception
{
    /// <summary>
    /// The status code identifying the error condition.
    /// </summary>
    public BlockNodeExceptionCode Code { get; private set; }
    /// <summary>
    /// Public Constructor.
    /// </summary>
    /// <param name="message">
    /// The message generated by the library describing the
    /// condition that raised the exception.
    /// </param>
    /// <param name="code">
    /// The status code identifying the error condition.
    /// </param>
    /// <param name="innerException">
    /// The inner exception that caused this exception, if any.
    /// </param>
    public BlockNodeException(string? message, BlockNodeExceptionCode code, Exception? innerException = null) : base(message, innerException)
    {
        Code = code;
    }
}
